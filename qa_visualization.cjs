const { chromium } = require('playwright');
const path = require('path');
const fs = require('fs');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL==='chromium'?undefined:(process.env.PLAYWRIGHT_CHANNEL||'msedge')});
  const page=await browser.newPage({viewport:{width:1100,height:1600}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('file:///'+path.resolve('results/preview.html').replaceAll('\\','/'));
  const frame=page.frameLocator('iframe');
  await frame.locator('#bbh-lab[data-ready="true"]').waitFor({timeout:60000});
  const baseline=await frame.locator('#bbh-median').textContent();
  await frame.locator('#bbh-spin').selectOption('0');
  const changed=await frame.locator('#bbh-median').textContent();
  if(changed===baseline)throw new Error('Spin interaction did not update posterior');
  await frame.locator('#bbh-spin').selectOption('1');
  await frame.locator('#bbh-event').selectOption({label:'GW190517_055101'});
  await frame.locator('#bbh-drop').check();
  const dropped=await frame.locator('#bbh-median').textContent();
  if(dropped===baseline)throw new Error('Leave-one-out did not update posterior');
  await frame.locator('#bbh-drop').uncheck();
  await frame.locator('#bbh-event').selectOption('');
  await frame.locator('#bbh-prior').selectOption('central');
  const priorChanged=await frame.locator('#bbh-median').textContent();
  if(priorChanged===baseline)throw new Error('Prior interaction did not update posterior');
  await frame.locator('#bbh-prior').selectOption('uniform');
  await frame.locator('#bbh-cal').focus();
  await frame.locator('#bbh-cal').press('End');
  const calibrationChanged=await frame.locator('#bbh-median').textContent();
  if(calibrationChanged===baseline)throw new Error('Selection perturbation did not update posterior');
  await frame.locator('#bbh-cal').press('Home');
  for(let i=0;i<10;i++)await frame.locator('#bbh-cal').press('ArrowRight');
  await frame.locator('#bbh-show-naive').click();
  if(await frame.locator('#bbh-show-naive').getAttribute('aria-pressed')!=='false')throw new Error('Legend toggle failed');
  await frame.locator('#bbh-show-naive').click();
  await page.waitForTimeout(250);
  await page.screenshot({path:'results/desktop.png',fullPage:true});
  const report={baseline,changed,dropped,priorChanged,calibrationChanged,errors,widths:[]};
  for(const width of [1024,736,360,320]){
    await page.setViewportSize({width,height:1800});
    await page.waitForTimeout(250);
    const result=await frame.locator('#bbh-lab').evaluate(root=>({client:root.clientWidth,scroll:root.scrollWidth,svg:[...root.querySelectorAll('.lab-plot svg')].map(s=>({width:s.getBoundingClientRect().width,axisTitles:s.querySelectorAll('text.axis-title').length})),bodyScroll:document.documentElement.scrollWidth,windowWidth:innerWidth}));
    report.widths.push({width,...result});
    if(result.scroll>result.client+2)throw new Error('Horizontal overflow at '+width);
  }
  await page.screenshot({path:'results/mobile.png',fullPage:true});
  await page.setViewportSize({width:1024,height:1600});
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
  await page.waitForTimeout(250);
  await page.screenshot({path:'results/dark.png',fullPage:true});
  fs.writeFileSync('results/ui_validation.json',JSON.stringify(report,null,2));
  await browser.close();console.log(JSON.stringify(report,null,2));
  if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
